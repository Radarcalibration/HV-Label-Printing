def get_cell_mfr_from_reess(reess: str) -> str | None:
    manufacturers = {
        cell_mfr
        for model_variants in battery_parameters.values()
        for manufacturers in model_variants.values()
        for cell_mfr, spec in manufacturers.items()
        if spec["pack_id_part_number"] == reess.strip().upper()
    }
    return next(iter(manufacturers)) if len(manufacturers) == 1 else None


def get_variant_from_reess(reess: str) -> str | None:
    pack_variants = {
        str(spec["pack_variant"])
        for model_variants in battery_parameters.values()
        for manufacturers in model_variants.values()
        for spec in manufacturers.values()
        if spec["pack_id_part_number"] == reess.strip().upper()
    }
    return next(iter(pack_variants)) if len(pack_variants) == 1 else None


